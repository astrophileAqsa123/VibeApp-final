const test = require('node:test');
const assert = require('node:assert/strict');

const {
  classifyBuildError,
  deterministicRepair,
  isEnvironmentFailure,
} = require('../services/selfHealingBuild');

test('classifies dependency errors', () => {
  const result = classifyBuildError("Error: Couldn't resolve the package 'foo' in 'package:foo/foo.dart'. Target of URI doesn't exist");
  assert.equal(result[0].type, 'dependency');
});

test('classifies undefined symbols', () => {
  const result = classifyBuildError("Error: The getter 'selectedRole' isn't defined for the type '_HomeState'.");
  assert.ok(result.some((item) => item.type === 'symbol'));
});

test('classifies environment failures and avoids code-repair classification', () => {
  const result = classifyBuildError('JAVA_HOME is not set and Gradle could not start');
  assert.equal(isEnvironmentFailure(result), true);
});

test('deterministically migrates deprecated button style API', () => {
  const input = "ElevatedButton(style: ElevatedButton.styleFrom(primary: Colors.blue), onPressed: () {}, child: const Text('Go'))";
  const result = deterministicRepair(input, 'The named parameter primary is not defined');
  assert.equal(result.changed, true);
  assert.match(result.updatedCode, /backgroundColor:/);
});

test('does not rewrite code when no deterministic rule matches', () => {
  const input = "void main() { runApp(const MyApp()); }";
  const result = deterministicRepair(input, 'Undefined name somethingElse');
  assert.equal(result.changed, false);
  assert.equal(result.updatedCode, input);
});


test('repairs JavaScript-style String.endsWith(RegExp) generated by AI', () => {
  const input = "if (_expression.endsWith(RegExp(r'[+\\-*/]'))) { return; }";
  const result = deterministicRepair(
    input,
    "Error: The argument type 'RegExp' can't be assigned to the parameter type 'String'."
  );
  assert.equal(result.changed, true);
  assert.match(result.updatedCode, /RegExp\(r'\[\+\\-\*\/\]\$'\)\.hasMatch\(_expression\)/);
  assert.doesNotMatch(result.updatedCode, /endsWith\(RegExp/);
});


test('deterministic repair fixes invalid Dart currency interpolation and numeric max list', () => {
  const code = "void main(){}\nfinal a = Text('$${amount}');\nfinal b = SimpleBars(maxValue:[food,travel,bills,other,1].reduce((a,b)=>a>b?a:b));";
  const result = deterministicRepair(code, 'Dart compile error');
  assert.equal(result.changed, true);
  assert.equal(result.updatedCode.includes("'\\$${amount}'"), true);
  assert.match(result.updatedCode, /maxValue:<double>\[food,travel,bills,other,1\.0\]/);
});

test('deterministic repair migrates Flutter-version-incompatible Color.withValues and dropdown initialValue', () => {
  const code = "final c = Colors.blue.withValues(alpha: .12);\nfinal d = DropdownButtonFormField<String>(initialValue: choice, items: const [], onChanged: (_) {});";
  const result = deterministicRepair(code, "The method 'withValues' isn't defined; No named parameter with the name 'initialValue'.");
  assert.equal(result.changed, true);
  assert.match(result.updatedCode, /withOpacity\(\.12\)/);
  assert.match(result.updatedCode, /DropdownButtonFormField<String>\(value: choice/);
  assert.doesNotMatch(result.updatedCode, /withValues\(/);
  assert.doesNotMatch(result.updatedCode, /initialValue:/);
});


test('deterministic repair fixes List<num> chart data passed to List<double>', () => {
  const code = "void main(){}\nfinal week=[1420.0,1780,1650,total.toDouble(),0.0];\nfinal chart=SimpleBars(values:week,labels:const ['M'],maxValue:2400.0);";
  const result = deterministicRepair(code, "Error: The argument type 'List<num>' can't be assigned to the parameter type 'List<double>'.");
  assert.equal(result.changed, true);
  assert.match(result.updatedCode, /final week=<double>\[/);
  assert.match(result.updatedCode, /1780\.0/);
  assert.match(result.updatedCode, /1650\.0/);
});
