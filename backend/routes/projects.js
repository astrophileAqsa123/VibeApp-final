/*
  GET /api/projects/:id
  Get single project with generated code
*/
router.get("/:id", auth, async (req, res) => {
  try {
    const userId = getUserId(req);

    const project = await Project.findOne({
      _id: req.params.id,
      user: userId
    });

    if (!project) {
      return res.status(404).json({
        message: "Project not found"
      });
    }

    // Auto-recover metadata and a snapshot for legacy projects created before
    // version history was captured on initial save.
    const activeCode = project.currentCode || project.generatedCode || "";
    const isSupabase = project.storageMode === "supabase" || isSupabaseCode(activeCode);
    let needsSave = false;

    if (isSupabase) {
      if (project.storageMode !== "supabase") {
        project.storageMode = "supabase";
        needsSave = true;
      }

      if (!project.tableSql || !project.tableSql.trim()) {
        const config = reconstructAppConfigFromCode(activeCode, project.prompt) || {};
        const extracted = extractSupabaseConfigFromCode(activeCode);
        const tableName =
          project.supabaseTable ||
          extracted.tableName ||
          config.tableName ||
          deriveTableName({ entity: config.entity || project.title });
        const fields = config.fields && config.fields.length > 0 ? config.fields : [];

        project.tableSql = generateTableSql(tableName, fields);
        if (!project.supabaseTable) {
          project.supabaseTable = tableName;
        }
        if (!project.supabaseUrl && extracted.supabaseUrl) {
          project.supabaseUrl = extracted.supabaseUrl;
        }
        needsSave = true;
      }

    }

    if (ensureCurrentVersionSnapshot(project)) {
      needsSave = true;
    }
    if (needsSave) {
      await project.save();
    }

    res.json({
      success: true,
      project
    });
  } catch (error) {
    console.error("Get project error:", error);

    res.status(500).json({
      message: "Failed to fetch project"
    });
  }
});

/*
  GET /api/projects/:id/engineering-report
  Static generation quality, capability, safety and readiness report.
  Runtime Flutter analyze/test/build remain explicitly pending until executed.
*/
router.get("/:id/engineering-report", auth, async (req, res) => {
  try {
    const userId = getUserId(req);
    const project = await Project.findOne({ _id: req.params.id, user: userId });
    if (!project) return res.status(404).json({ success: false, message: "Project not found" });

    const rawSpec = project.appSpec || project.appConfig || null;
    let spec = rawSpec;
    if (rawSpec && typeof rawSpec === "object") {
      try { spec = normalizeAndValidateAppSpec(rawSpec, { storageMode: project.storageMode || "local" }).spec; } catch { spec = rawSpec; }
    }
    const report = buildEngineeringReport({
      prompt: project.latestPrompt || project.prompt,
      spec,
      code: project.currentCode || project.generatedCode,
      storageMode: project.storageMode || "local",
      source: project.generationSource || "",
      tableSql: project.tableSql || "",
    });
    return res.json({ success: true, report });
  } catch (error) {
    console.error("Engineering report error:", error);
    return res.status(500).json({ success: false, message: "Failed to create engineering report" });
  }
});

/*
  GET /api/projects/:id/versions/diff?from=1&to=2
  Structural AppSpec diff. Falls back gracefully when legacy versions lack specs.
*/
router.get("/:id/versions/diff", auth, async (req, res) => {
  try {
    const userId = getUserId(req);
    const project = await Project.findOne({ _id: req.params.id, user: userId });
    if (!project) return res.status(404).json({ success: false, message: "Project not found" });
    const versions = Array.isArray(project.versions) ? project.versions : [];
    const fromNumber = Number(req.query.from || Math.max(1, (project.version || 1) - 1));
    const toNumber = Number(req.query.to || project.version || 1);
    const from = versions.find((item) => item.version === fromNumber);
    const to = versions.find((item) => item.version === toNumber);
    if (!from || !to) return res.status(404).json({ success: false, message: "Requested version snapshot was not found" });
    const before = from.appSpec || from.appConfig || null;
    const after = to.appSpec || to.appConfig || null;
    return res.json({ success: true, from: fromNumber, to: toNumber, diff: diffAppSpecs(before, after) });
  } catch (error) {
    console.error("Version diff error:", error);
    return res.status(500).json({ success: false, message: "Failed to compare versions" });
  }
});

