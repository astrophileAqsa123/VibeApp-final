/*
  POST /api/projects
  Create a new project
*/
router.post("/", auth, async (req, res) => {
  try {
    const userId = getUserId(req);

    if (!userId) {
      return res.status(401).json({
        message: "User not found in token",
      });
    }

    const {
      prompt = "",
      code = "",
      title = "Untitled Project",
      source = "",
      // Supabase fields (optional — only sent when user enables Supabase toggle)
      storageMode = "local",
      supabaseUrl = "",
      supabaseAnonKey = "",
      supabaseTable = "",
      tableSql = "",
      appConfig = null,
      appSpec = null,
      requirements = [],
      componentPlan = [],
      fileManifest = [],
      entrypoint = "lib/main.dart",
    } = req.body;

    if (!String(code || "").trim()) {
      return res.status(400).json({
        success: false,
        message: "Generated Flutter code is required.",
      });
    }

    let effectiveStorageMode = storageMode;
    let effectiveTableSql = tableSql;
    let effectiveTableName = supabaseTable;
    let effectiveUrl = supabaseUrl;

    if (effectiveStorageMode === "supabase" || isSupabaseCode(code)) {
      effectiveStorageMode = "supabase";
      if (!effectiveTableSql || !effectiveTableSql.trim()) {
        const config = reconstructAppConfigFromCode(code, prompt) || {};
        const extracted = extractSupabaseConfigFromCode(code);
        effectiveTableName = effectiveTableName || extracted.tableName || config.tableName || deriveTableName({ entity: config.entity || title });
        const fields = config.fields && config.fields.length > 0 ? config.fields : [];
        effectiveTableSql = generateTableSql(effectiveTableName, fields);
        if (!effectiveUrl && extracted.supabaseUrl) {
          effectiveUrl = extracted.supabaseUrl;
        }
      }
    }

    const project = new Project({
      user: userId,
      title: String(title).slice(0, 100),
      prompt,
      latestPrompt: prompt,
      generatedCode: code,
      currentCode: code,
      generationSource: source,
      status: "generated",
      version: 1,
      // Supabase fields — safe defaults for non-Supabase projects
      storageMode: effectiveStorageMode,
      supabaseUrl: effectiveUrl,
      supabaseAnonKey,
      supabaseTable: effectiveTableName,
      tableSql: effectiveTableSql,
      appConfig: appConfig && typeof appConfig === "object" ? appConfig : null,
      appSpec: appSpec && typeof appSpec === "object" ? appSpec : null,
      requirements: Array.isArray(requirements) ? requirements : [],
      componentPlan: Array.isArray(componentPlan) ? componentPlan : [],
      fileManifest: Array.isArray(fileManifest) ? fileManifest : [],
      entrypoint: String(entrypoint || "lib/main.dart"),
      versions: [
        buildProjectVersion({
          version: 1,
          prompt,
          source,
          generatedCode: code,
          storageMode: effectiveStorageMode,
          tableSql: effectiveTableSql,
          supabaseTable: effectiveTableName,
          appConfig,
          appSpec,
          requirements,
          componentPlan,
          fileManifest,
          entrypoint,
        }),
      ],
    });

    await project.save();

    res.status(201).json({
      success: true,
      project,
    });
  } catch (error) {
    console.error("Create project error:", error);

    res.status(500).json({
      message: "Failed to create project",
    });
  }
});

