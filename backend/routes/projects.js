/*
  GET /api/projects/:id/export
  Download Flutter ZIP project
*/
router.get("/:id/export", auth, async (req, res) => {
  try {
    const userId = getUserId(req);

    const project = await Project.findOne({
      _id: req.params.id,
      user: userId
    });

    if (!project) {
      return res.status(404).json({
        message: "Project not found"
      });
    }

    const safeTitle = project.title.replace(/[^a-z0-9_]/gi, "_").toLowerCase();
    const tempDir = path.join(__dirname, "..", "temp", project._id.toString());

    buildFlutterProject(tempDir, {
      title: project.title,
      safeTitle,
      code: project.currentCode || project.generatedCode,
      storageMode: project.storageMode || 'local',
    });

    const zipName = `${safeTitle}.zip`;

    res.setHeader(
      "Content-Type",
      "application/zip"
    );

    res.setHeader(
      "Content-Disposition",
      `attachment; filename=${zipName}`
    );

    const archive = archiver("zip", {
      zlib: { level: 9 }
    });

    archive.pipe(res);

    archive.directory(tempDir, false);

    await archive.finalize();

  } catch (error) {
    console.error(error);

    res.status(500).json({
      message: "Export failed"
    });
  }
});
